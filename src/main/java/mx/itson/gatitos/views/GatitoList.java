    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tblGatitos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona un gatito de la tabla para editar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Gatito gatitoSeleccionado = new Gatito();
        gatitoSeleccionado.setId(Integer.parseInt(tblGatitos.getValueAt(fila, 0).toString()));
        gatitoSeleccionado.setNombre(tblGatitos.getValueAt(fila, 1).toString());
        gatitoSeleccionado.setRaza(tblGatitos.getValueAt(fila, 2).toString());
        gatitoSeleccionado.setEdad(Integer.parseInt(tblGatitos.getValueAt(fila, 3).toString()));
        gatitoSeleccionado.setColor(tblGatitos.getValueAt(fila, 4).toString());

        GatitoForm form = new GatitoForm(this, true, gatitoSeleccionado);
        form.setVisible(true);
        cargarGatitos();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblGatitos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona un gatito de la tabla para eliminar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = Integer.parseInt(tblGatitos.getValueAt(fila, 0).toString());
        String nombre = tblGatitos.getValueAt(fila, 1).toString();

        int confirmacion = JOptionPane.showConfirmDialog(
                this,
                "¿Seguro que deseas eliminar a " + nombre + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmacion != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(API_BASE_URL + "/gatitos/delete/" + id))
                    .DELETE()
                    .build();

            HttpClient client = HttpClient.newHttpClient();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            ResultDto result = new Gson().fromJson(response.body(), ResultDto.class);
            if (response.statusCode() >= 200 && response.statusCode() < 300 && result != null && result.isSuccess()) {
                JOptionPane.showMessageDialog(this, result.getMessage(), "Éxito", JOptionPane.INFORMATION_MESSAGE);
                cargarGatitos();
            } else {
                String msg = (result != null && result.getMessage() != null)
                        ? result.getMessage()
                        : "Código HTTP: " + response.statusCode();
                JOptionPane.showMessageDialog(this, "No se pudo eliminar: " + msg, "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IOException | InterruptedException ex) {
            JOptionPane.showMessageDialog(this, "Error al conectar con la API: " + ex.getMessage(), "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

