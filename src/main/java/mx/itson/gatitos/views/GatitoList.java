    public final void cargarGatitos() {
        try {
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(API_BASE_URL + "/gatitos"))
                    .GET()
                    .build();

            HttpClient client = HttpClient.newHttpClient();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            if (response.statusCode() == 200) {
                Gson gson = new Gson();
                Gatito[] gatitos = gson.fromJson(response.body(), Gatito[].class);

                DefaultTableModel model = (DefaultTableModel) tblGatitos.getModel();
                model.setRowCount(0);

                if (gatitos != null) {
                    for (Gatito g : gatitos) {
                        model.addRow(new Object[]{
                            g.getId(),
                            g.getNombre(),
                            g.getRaza(),
                            g.getEdad(),
                            g.getColor()
                        });
                    }
                }
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "La API respondió con código: " + response.statusCode(),
                        "Error al cargar gatitos",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        } catch (IOException | InterruptedException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo conectar con la API en " + API_BASE_URL + ".\n"
                    + "Asegúrate de iniciar el servidor Django (python manage.py runserver).",
                    "Error de conexión",
                    JOptionPane.WARNING_MESSAGE
            );
        }
    }

