    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText().trim();
        String raza = txtRaza.getText().trim();
        String edadTexto = txtEdad.getText().trim();
        String color = txtColor.getText().trim();

        if (nombre.isEmpty() || raza.isEmpty() || edadTexto.isEmpty() || color.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor completa todos los campos.", "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int edad;
        try {
            edad = Integer.parseInt(edadTexto);
            if (edad < 0) {
                JOptionPane.showMessageDialog(this, "La edad no puede ser negativa.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Ingresa un número válido para la edad.", "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Gatito gatito = new Gatito();
            boolean esEdicion = (this.gatitoEditar != null && this.gatitoEditar.getId() > 0);
            gatito.setId(esEdicion ? this.gatitoEditar.getId() : 0);
            gatito.setNombre(nombre);
            gatito.setRaza(raza);
            gatito.setEdad(edad);
            gatito.setColor(color);

            Gson gson = new Gson();
            String json = gson.toJson(gatito);

            HttpRequest.Builder builder = HttpRequest.newBuilder()
                    .header("Content-Type", "application/json");

            if (esEdicion) {
                builder.uri(URI.create(API_BASE_URL + "/gatitos/edit"))
                        .PUT(HttpRequest.BodyPublishers.ofString(json));
            } else {
                builder.uri(URI.create(API_BASE_URL + "/gatitos/save"))
                        .POST(HttpRequest.BodyPublishers.ofString(json));
            }

            HttpClient client = HttpClient.newHttpClient();
            HttpResponse<String> response = client.send(builder.build(), HttpResponse.BodyHandlers.ofString());

            ResultDto result = gson.fromJson(response.body(), ResultDto.class);
            if (response.statusCode() >= 200 && response.statusCode() < 300 && result != null && result.isSuccess()) {
                JOptionPane.showMessageDialog(this, result.getMessage(), "Éxito", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            } else {
                String msg = (result != null && result.getMessage() != null)
                        ? result.getMessage()
                        : "Código HTTP: " + response.statusCode();
                JOptionPane.showMessageDialog(this, "No se pudo guardar: " + msg, "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IOException | InterruptedException ex) {
            JOptionPane.showMessageDialog(this, "Error al conectar con la API: " + ex.getMessage(), "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

